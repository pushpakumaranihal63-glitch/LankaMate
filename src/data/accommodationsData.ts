/**
 * Converts accommodation records into NearMePlace format for the Near Me view.
 */
export function getAccommodationNearMePlaces(): NearMePlace[] {
  return SRI_LANKAN_ACCOMMODATIONS.map((acc) => ({
    id: acc.id,
    name: acc.name,
    category: 'hotel' as const,
    categoryLabel: acc.accommodationType,
    city: acc.city,
    area: acc.area,
    address: acc.address,
    coordinates: acc.coordinates,
    openStatus: acc.openStatus,
    openingHours: acc.openingHours,
    contactPhone: acc.contactPhone,
    services: acc.services,
    description: acc.description,
    drivingTip: acc.drivingTip,
    rating: acc.rating,
    isFeatured: acc.isFeatured,
    searchKeywords: `${acc.name} ${acc.city} ${acc.area} ${acc.accommodationType} hotel resort homestay villa guest house hostel bungalow lodge`,
    image: acc.image,
    accommodationType: acc.accommodationType,
  }));
}

/**
 * Converts accommodation records into Hotel format for the HotelsView and booking catalog.
 */
export function getAccommodationHotels(): Hotel[] {
  return SRI_LANKAN_ACCOMMODATIONS.map((acc) => ({
    id: acc.id,
    name: acc.name,
    destinationId: acc.city.toLowerCase().replace(/\s+/g, '-'),
    destinationName: `${acc.city}${acc.area ? ` / ${acc.area}` : ''}`,
    region: acc.region,
    image: acc.image,
    rating: acc.rating,
    reviewsCount: acc.reviewsCount,
    starRating: acc.starRating,
    pricePerNightLkr: acc.pricePerNightLkr,
    pricePerNightUsd: acc.pricePerNightUsd,
    badge: acc.badge,
    hotelType: acc.accommodationType,
    description: acc.description,
    facilities: acc.facilities,
    roomTypes: acc.roomTypes,
    bookingUrl: `https://www.google.com/travel/hotels?q=${encodeURIComponent(acc.name + ' ' + acc.city + ' Sri Lanka')}`,
    coordinates: acc.coordinates,
  }));
}
